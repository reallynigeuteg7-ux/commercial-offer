import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
const root = path.dirname(fileURLToPath(import.meta.url));
const tools = process.env.FACADE_BUILD_TOOLS || root;
const require = createRequire(path.join(tools, 'package.json'));
const { build } = require('esbuild');
const { packager } = await import(pathToFileURL(require.resolve('@electron/packager')).href);
const electronVersion = require('electron/package.json').version;
const output = path.resolve(process.env.FACADE_BUILD_OUTPUT || path.join(root, 'dist'));
const staging = path.join(output, 'app-source');
await fs.mkdir(path.join(staging,'ui'), {recursive:true});
await build({entryPoints:[path.join(root,'main.mjs')],bundle:true,platform:'node',format:'cjs',external:['electron'],target:'node22',outfile:path.join(staging,'main.cjs')});
await build({entryPoints:[path.join(root,'ui/app.js')],bundle:true,platform:'browser',target:'chrome130',outfile:path.join(staging,'ui/app.js')});
await fs.copyFile(path.join(root,'preload.cjs'),path.join(staging,'preload.cjs'));
for (const name of ['index.html','style.css']) await fs.copyFile(path.join(root,'ui',name),path.join(staging,'ui',name));
await fs.copyFile(path.join(root,'../public/facade-mark-black.svg'),path.join(staging,'ui/logo.svg'));
await fs.copyFile(path.join(root,'brand.ico'),path.join(staging,'brand.ico'));
await fs.writeFile(path.join(staging,'package.json'),JSON.stringify({name:'facade-documents',productName:'Facade Documents',version:'1.2.0',description:'КП и ПП для Facade Kazakhstan',main:'main.cjs',author:'Facade Kazakhstan',license:'UNLICENSED'}));
const paths = await packager({dir:staging,icon:path.join(root,'brand.ico'),out:output,name:'Facade Documents',platform:'win32',arch:'x64',electronVersion,asar:true,overwrite:true,prune:false,executableName:'Facade Documents',appCopyright:'Facade Kazakhstan',win32metadata:{CompanyName:'Facade Kazakhstan',FileDescription:'КП и ПП — Facade Kazakhstan',ProductName:'Facade Documents'}});
await fs.copyFile(path.join(root,'ИНСТРУКЦИЯ.txt'),path.join(paths[0],'ИНСТРУКЦИЯ.txt'));
await fs.copyFile(path.join(root,'brand.ico'),path.join(paths[0],'brand-transparent.ico'));
console.log(JSON.stringify({electronVersion,path:paths[0]}));
